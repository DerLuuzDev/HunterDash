    t(key) {
        const lang = window.SettingsManager?.settings?.language || 'de';
        return this.translations[lang]?.[key] || this.translations['de'][key] || key;
    },

    updateAll() {
        document.querySelectorAll('[data-i18n]').forEach(el => {
            const key = el.getAttribute('data-i18n');
            const text = this.t(key);
            if (el.tagName === 'INPUT' && el.type === 'text') {
                el.placeholder = text;
            } else {
                // Preserve emojis at the start
                const currentText = el.textContent;
                const emojiMatch = currentText.match(/^[\p{Emoji}\s]+/u);
                const emoji = emojiMatch ? emojiMatch[0].trim() + ' ' : '';
                el.textContent = emoji + text;
            }
        });
    }
